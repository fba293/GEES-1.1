/**
 * Adapts LanguageCenterItem records into University-compatible objects so the
 * shared Leaflet UniversityMap renders every center cleanly with clustering & popups.
 */
export function languageCentersToMapRecords(centers: LanguageCenterItem[]): University[] {
  return centers.map((lc) => ({
    id: lc.id,
    name: lc.name,
    slug: lc.slug,
    country: lc.country,
    countryCode: 'MY',
    flagEmoji: lc.flagEmoji,
    city: lc.city,
    state: lc.city,
    established: lc.establishedYear,
    type: lc.studentVisaSupported ? 'EMGS Language Centre' : 'Language Centre',
    tagline: lc.tagline,
    description: lc.overview,
    logoUrl: '',
    bannerUrl: '',
    campuses: [
      {
        id: `${lc.id}-campus`,
        name: `${lc.name} — ${lc.city}`,
        city: lc.city,
        stateOrProvince: lc.city,
        country: lc.country,
        isMainCampus: true,
      },
    ],
    intakes: lc.intakes,
    avgTuitionAnnualUSD: lc.monthlyFeeUSD * 12,
    currency: 'USD',
    minIeltsScore: 0,
    acceptanceRatePct: 98,
    popularPrograms: lc.programs,
    scholarshipsAvailable: false,
    featured: Boolean(lc.featured),
    topRanked: lc.rating >= 4.85,
  }));
}
